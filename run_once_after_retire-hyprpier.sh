#!/bin/bash
# hyprpier retired (runs once): strand/monitors.strand arranges the monitors and
# the launcher's Thunderbolt page lets docks in (bolt decides who may connect).
# Needs strand edge d9d726f4 or newer running first (README, Monitors).
set -e

# Its daemon would write monitors.lua again on the next dock.
pkill -f '^hyprpier daemon' || true

# Strand never writes over a file it didn't write: hyprpier's goes, and Strand,
# trying again every few seconds, writes its own in its place.
f="$HOME/.config/hypr/monitors.lua"
if head -n1 "$f" 2>/dev/null | grep -q '^-- Generated by hyprpier'; then rm -f "$f"; fi

# Its udev rule lets every Thunderbolt device in, and its resume service lets
# every one back in after sleep; thunderbolt-resume.service (setup script)
# keeps the reset and only lets back in what bolt let in.
if [ -e /etc/udev/rules.d/99-hyprpier.rules ] || [ -e /etc/systemd/system/hyprpier-resume.service ]; then
    echo "Removing hyprpier's udev rule and resume service. This requires sudo."
    if [ -e /etc/systemd/system/hyprpier-resume.service ]; then
        sudo systemctl disable hyprpier-resume.service
        sudo rm /etc/systemd/system/hyprpier-resume.service
        sudo systemctl daemon-reload
    fi
    if [ -e /etc/udev/rules.d/99-hyprpier.rules ]; then
        sudo rm /etc/udev/rules.d/99-hyprpier.rules
        sudo udevadm control --reload
    fi
fi
echo "hyprpier retired: uninstall it with 'yay -R hyprpier-git'."
